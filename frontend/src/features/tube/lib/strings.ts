export const TUBE_TABLES: Record<Lang, Record<TubeKey, string>> = { en, zh, es, ja, ko }

export type TubeTranslate = (key: TubeKey, vars?: Record<string, string | number>) => string

export function tubeTranslator(lang: Lang): TubeTranslate {
  const table = TUBE_TABLES[lang]
  return (key, vars = {}) => table[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

/** The tube strings in the app's current language, plus that language. */
export function useTubeT(): { t: TubeTranslate; lang: Lang } {
  const { lang } = useT()
  return { t: tubeTranslator(lang), lang }
}
